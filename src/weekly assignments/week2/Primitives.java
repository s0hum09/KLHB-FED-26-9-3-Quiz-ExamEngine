public class Primitives {
    public static void main(String[] args) {
        int lockerCount = 120; 
        double storageFee = 15.50; 
        char sizeTier = 'L'; 
        boolean isFragile = true; 
        int maxWeight = 25; 

        System.out.println("lockers   = " + lockerCount);
        System.out.println("fee       = " + storageFee);
        System.out.println("tier      = " + sizeTier);
        System.out.println("fragile   = " + isFragile);
        System.out.println("maxWeight = " + maxWeight + " kg");
    }
}